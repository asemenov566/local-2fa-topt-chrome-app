import {readdir,readFile,writeFile,mkdir,lstat} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {build} from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const directory = path.join(root,'extension/strategy');
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Only --check is supported.');
const entries = (await readdir(directory,{withFileTypes:true})).filter(entry => entry.name.endsWith('.js') && entry.name !== 'registry.js').sort((a,b) => a.name.localeCompare(b.name,'en'));
if (!entries.length) throw new Error('At least one site strategy is required.');
if ((await lstat(directory)).isSymbolicLink()) throw new Error('The strategy directory must not be a link.');
const definitions = [], seenOrigins = new Set();
for (const entry of entries) {
  if (!entry.isFile() || !/^[a-z][a-z0-9-]*\.js$/.test(entry.name)) throw new Error('Strategy filenames must be lowercase service IDs followed by .js.');
  const Strategy = (await import(pathToFileURL(path.join(directory,entry.name)))).default;
  const id = entry.name.slice(0,-3);
  if (typeof Strategy !== 'function' || Strategy.id !== id || typeof Strategy.displayName !== 'string' || !Strategy.displayName.trim() || Strategy.displayName.length > 80 || /[\u0000-\u001f\u007f]/u.test(Strategy.displayName)) throw new Error('Invalid strategy class or display metadata: '+id);
  if (typeof Strategy.customDomain !== 'boolean') throw new Error('customDomain must be boolean: '+id);
  if (Strategy.customDomain) {
    if (Strategy.domain !== null) throw new Error('Custom-domain strategies must use domain: null.');
  } else {
    let url; try { url = new URL(Strategy.domain); } catch { throw new Error('Fixed strategy domain must be an HTTPS origin: '+id); }
    if (url.protocol !== 'https:' || url.origin !== Strategy.domain || url.username || url.password || url.port || !url.hostname.includes('.') || url.hostname.includes('*')) throw new Error('Fixed strategy domain must be an exact HTTPS origin: '+id);
    if (seenOrigins.has(Strategy.domain)) throw new Error('Fixed strategy origins must be unique.');
    seenOrigins.add(Strategy.domain);
  }
  for (const method of ['isAuthPage','fields','loginAction','authTarget','submit']) if (typeof Strategy.prototype[method] !== 'function') throw new Error('Missing strategy method '+method+': '+id);
  if (typeof Strategy.route !== 'function') throw new Error('Missing static route method: '+id);
  definitions.push({id,file:entry.name,displayName:Strategy.displayName,domain:Strategy.domain,customDomain:Strategy.customDomain});
}
const registry = '// Generated by npm run build:strategies. Edit individual strategy classes.\n' +
  definitions.map((d,i) => `import Strategy${i} from './${d.file}';`).join('\n') + '\n' +
  `export const strategyClasses = Object.freeze([${definitions.map((_,i) => 'Strategy'+i).join(',')}]);\n` +
  `const byId = new Map(strategyClasses.map(Strategy => [Strategy.id,Strategy]));\n` +
  `export function getStrategy(id) { return byId.get(id) ?? null; }\n` +
  `export const strategyOptions = Object.freeze(strategyClasses.map(({id,domain,displayName,customDomain}) => Object.freeze({id,domain,displayName,customDomain})));\n` +
  `export function strategyScripts(id) { return byId.has(id) ? ['generated/'+id+'.js'] : []; }\n` +
  `export function strategyRoute(id,url,otp=false) { const Strategy = getStrategy(id); if (!Strategy) return false; try { return Strategy.route(url,otp) === true; } catch { return false; } }\n`;
const outputs = new Map([['extension/strategy/registry.js',registry]]);
for (const {id,file} of definitions) {
  const result = await build({stdin:{contents:`import Strategy from './strategy/${file}'; import {start} from './autofill.js'; start(new Strategy());`,resolveDir:path.join(root,'extension'),sourcefile:'strategy-entry.js',loader:'js'},bundle:true,write:false,format:'iife',platform:'browser',target:'chrome120',minify:true,legalComments:'none'});
  outputs.set('extension/generated/'+id+'.js',result.outputFiles[0].text);
}
const files = ['extension/strategy/registry.js',...definitions.map(d => 'extension/strategy/'+d.file),...definitions.map(d => 'extension/generated/'+d.id+'.js')];
outputs.set('scripts/strategy-files.json',JSON.stringify({version:1,files},null,2)+'\n');
for (const [relative,content] of outputs) {
  const target = path.join(root,relative);
  if (check) {
    const existing = await readFile(target,'utf8').catch(() => null);
    if (existing?.replace(/\r\n/g,'\n') !== content) throw new Error('Generated strategy file is out of date: '+relative);
  } else {
    await mkdir(path.dirname(target),{recursive:true});
    await writeFile(target,content,'utf8');
  }
}
console.log(`${check ? 'Verified' : 'Built'} ${definitions.length} site strategies.`);
